# Run the deployed explorer locally so it can be inspected before sign-off.
# Builds the three images if they are missing, then serves the whole thing on
# one origin at http://localhost:${PREVIEW_PORT:-20050}.
#
#   up      build if needed, start, wait until it serves, print what to check
#   check   assert the lockdown decisions actually hold on the running stack
#   logs    follow the backend
#   down    stop and remove the volume
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="${REPO_DIR}/docker-compose.preview.yml"
ENV_FILE="${REPO_DIR}/.env.preview"
PORT="${PREVIEW_PORT:-20050}"
BASE="http://localhost:${PORT}"

dc() { docker compose --env-file "${ENV_FILE}" -f "${COMPOSE_FILE}" "$@"; }
log() { printf '[preview] %s\n' "$*" >&2; }

gen_env() {
    [ -f "${ENV_FILE}" ] && return
    log "generating ${ENV_FILE}"
    umask 077
    cat >"${ENV_FILE}" <<EOF
# Generated by scripts/preview.sh — throwaway local values, gitignored.
POSTGRES_PASSWORD=$(openssl rand -hex 16)
SECRET_KEY_BASE=$(openssl rand -hex 64)
PREVIEW_PORT=${PORT}
EOF
}

build_if_missing() {
    for role in api ui proxy; do
        if ! docker image inspect "quip-explorer-${role}:local" >/dev/null 2>&1; then
            log "building quip-explorer-${role}:local"
            docker build -q -f "${REPO_DIR}/Dockerfile.${role}" \
                --build-arg BAKE_PROD_ENV=1 \
                -t "quip-explorer-${role}:local" "${REPO_DIR}" >/dev/null
        fi
    done
}

cmd_up() {
    gen_env; build_if_missing
    dc up -d
    # Wait for the FRONTEND, not just the API. The Next.js image spends a
    # couple of minutes downloading assets and validating env before it binds,
    # and nginx 502s the whole site until it does. Waiting only on
    # /api/v2/stats reports "up" while / is still broken — which is worse than
    # a slower start, because it sends you to a page that looks deployed and
    # is not.
    log "waiting for the API..."
    until curl -sS -o /dev/null --max-time 3 "${BASE}/api/v2/stats" 2>/dev/null; do sleep 3; done
    log "waiting for the frontend (it validates env and fetches assets first, ~2 min)..."
    local n=0
    until [ "$(curl -sS -o /dev/null -w '%{http_code}' --max-time 5 "${BASE}/" 2>/dev/null)" = "200" ]; do
        n=$(( n + 1 ))
        if [ "${n}" -gt 120 ]; then
            log "ERROR: frontend never became ready. Last few lines:"
            docker logs qep-bsui 2>&1 | tail -15 >&2
            return 1
        fi
        sleep 3
    done
    cat >&2 <<EOF

  Explorer is up:  ${BASE}

  It starts from an empty database. Recent blocks appear within about a
  minute; the ~109k blocks of history backfill behind that over ~2 hours.
  You do not need to wait for that to judge the UI.

  Worth looking at:
    ${BASE}/                     home — blocks should start appearing
    ${BASE}/blocks               block list
    ${BASE}/api-docs             API docs (deliberately kept enabled)
    ${BASE}/api/v2/stats         raw API

  Things that should NOT be there — the point of the lockdown:
    no ad banner or text ads anywhere on the page
    no Marketplace / DappScout in the nav
    no gas tracker widget
    ${BASE}/graphiql             must 404
    ${BASE}/metrics              must 404

  'scripts/preview.sh check' asserts all of that automatically.
  'scripts/preview.sh down' stops it and removes the volume.

EOF
}

# Asserts the decisions hold on the RUNNING stack. Fails closed and loud: this
# is the evidence for sign-off, so a check that cannot run is a failure, not a
# silent pass.
cmd_check() {
    local fail=0
    ok()  { printf '  PASS  %s\n' "$1"; }
    bad() { printf '  FAIL  %s\n' "$1"; fail=1; }

    code() { curl -sS -o /dev/null -w '%{http_code}' --max-time 10 "${BASE}$1" 2>/dev/null || echo 000; }

    # A 502 means the frontend has not bound yet, and every routing assertion
    # below would then "pass" for the wrong reason — /metrics 404s because the
    # frontend 404s it, not because nginx blocked it. Refuse to report on a
    # half-started stack.
    if [ "$(code /)" = "502" ]; then
        echo "  stack is still starting (/ returns 502 — frontend not bound yet)."
        echo "  wait for 'scripts/preview.sh up' to finish, then re-run check."
        return 1
    fi

    echo "=== must be blocked ==="
    [ "$(code /graphiql)" = "404" ] && ok "/graphiql is 404" || bad "/graphiql returned $(code /graphiql)"
    [ "$(code /api/v1/graphql)" = "404" ] && ok "/api/v1/graphql is 404" || bad "/api/v1/graphql returned $(code /api/v1/graphql)"
    [ "$(code /metrics)" = "404" ] && ok "/metrics is 404" || bad "/metrics returned $(code /metrics)"
    local gq
    gq="$(curl -sS --max-time 10 -X POST -H 'content-type: application/json' \
        -d '{"query":"{ __schema { queryType { name } } }"}' "${BASE}/api/v1/graphql" 2>/dev/null || true)"
    case "${gq}" in
        *RootQueryType*) bad "GraphQL introspection STILL WORKS through the proxy" ;;
        *) ok "GraphQL introspection is refused" ;;
    esac

    echo "=== must work ==="
    for p in / /api/v2/stats /api-docs /sitemap.xml; do
        [ "$(code "$p")" = "200" ] && ok "$p is 200" || bad "$p returned $(code "$p")"
    done

    echo "=== frontend feature lockdown (from the image's own boot checklist) ==="
    local on
    on="$(docker logs qep-bsui 2>&1 | grep -E '^\s*\[v\]' | sed 's/^ *\[v\] //' || true)"
    if [ -z "${on}" ]; then bad "could not read the frontend checklist"; else
        printf '%s\n' "${on}" | sed 's/^/        enabled: /'
        printf '%s\n' "${on}" | grep -qiE 'banner ads|text ads' && bad "ADS ARE ENABLED" || ok "no ads enabled"
        printf '%s\n' "${on}" | grep -qi 'marketplace' && bad "marketplace enabled" || ok "marketplace off"
        printf '%s\n' "${on}" | grep -qi 'gas tracker' && bad "gas tracker enabled" || ok "gas tracker off"
    fi

    echo "=== indexer fetchers actually running ==="
    docker logs qep-bsapi 2>&1 | grep -o '"fetcher":"[a-z_]*"' | sort -u | sed 's/^/        /' || true
    docker logs qep-bsapi 2>&1 | grep -qi "empty blocks" && bad "empty-blocks sanitizer is running" || ok "empty-blocks sanitizer silent"

    echo
    [ "${fail}" -eq 0 ] && echo "ALL CHECKS PASSED" || { echo "THERE WERE FAILURES"; return 1; }
}

case "${1:-}" in
    up)    cmd_up ;;
    check) cmd_check ;;
    logs)  dc logs -f bsapi ;;
    down)  dc down --volumes --remove-orphans; log "down, volume removed" ;;
    *) echo "usage: $0 {up|check|logs|down}" >&2; exit 2 ;;
esac
