# QUI-992 rehearsal driver. Brings up Blockscout against the live testnet EVM
# endpoint and samples the four numbers the deploy needs sized on:
#
#   1. wall-clock to backfill from FIRST_BLOCK to head
#   2. peak backend RSS
#   3. peak Postgres RSS
#   4. pg_database_size at head
#
# Subcommands:
#   up       generate secrets (once), pull, start the stack
#   sample   append one metrics row to rehearsal/metrics.csv and print it
#   watch    sample every INTERVAL seconds until caught up (for a Monitor)
#   status   one-line human summary
#   logs     follow bsapi logs
#   down     stop and REMOVE the volume (a rerun re-backfills from scratch)
#
# Secrets live in .env.rehearsal, which is gitignored and generated on first
# `up`. They are throwaway rehearsal values and are NOT the ones the deployed
# app gets — SECRET_KEY_BASE is regenerated for the real deploy.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="${REPO_DIR}/docker-compose.rehearsal.yml"
ENV_FILE="${REPO_DIR}/.env.rehearsal"
OUT_DIR="${REPO_DIR}/rehearsal"
CSV="${OUT_DIR}/metrics.csv"
START_MARKER="${OUT_DIR}/.started_at"

RPC="${QUIP_EVM_RPC_HTTP:-https://evm-rpc.testnet.quip.network:20049/}"
FIRST_BLOCK="${QUIP_FIRST_BLOCK:-985665}"
INTERVAL="${INTERVAL:-60}"

dc() { docker compose --env-file "${ENV_FILE}" -f "${COMPOSE_FILE}" "$@"; }

log() { printf '[rehearse] %s\n' "$*" >&2; }

# ── secrets ─────────────────────────────────────────────────────────────────
gen_env() {
    if [ -f "${ENV_FILE}" ]; then
        log "using existing ${ENV_FILE}"
        return
    fi
    log "generating ${ENV_FILE}"
    # SECRET_KEY_BASE must be 64 bytes; Blockscout refuses shorter values.
    umask 077
    cat >"${ENV_FILE}" <<EOF
# Generated by scripts/rehearse.sh — throwaway REHEARSAL values, gitignored.
# The deployed app gets a freshly generated SECRET_KEY_BASE, not this one.
POSTGRES_PASSWORD=$(openssl rand -hex 16)
SECRET_KEY_BASE=$(openssl rand -hex 64)
EOF
}

# ── chain head, straight from the RPC ───────────────────────────────────────
rpc_head() {
    local hex
    hex="$(curl -sS --max-time 15 -X POST -H 'content-type: application/json' \
        -d '{"jsonrpc":"2.0","id":1,"method":"eth_blockNumber","params":[]}' \
        "${RPC}" 2>/dev/null | grep -o '"result":"0x[0-9a-f]*"' | cut -d'"' -f4)" || true
    [ -n "${hex:-}" ] || { echo ""; return; }
    printf '%d' "${hex}"
}

# ── one psql round trip for every DB number we want ─────────────────────────
# MIN/MAX/COUNT over consensus blocks, plus the on-disk size. COUNT is the
# metric that matters: Blockscout's catchup fetcher walks DOWN from head toward
# FIRST_BLOCK, so MAX(number) reaches head almost immediately and says nothing
# about progress.
db_stats() {
    docker exec qer-bsdb psql -U blockscout -d blockscout -At -F',' -c "
      SELECT COALESCE(MIN(number),0),
             COALESCE(MAX(number),0),
             COUNT(*),
             pg_database_size('blockscout')
      FROM blocks WHERE consensus = true;" 2>/dev/null || echo ""
}

# ── container memory/cpu, normalised to bytes ───────────────────────────────
# docker stats prints MemUsage as e.g. "1.234GiB / 30.4GiB"; take the first
# field and convert. Docker Desktop runs containers in a VM, so host cgroup
# paths are not readable from here — docker stats is the portable source.
mem_bytes() {
    docker stats --no-stream --format '{{.Name}}|{{.MemUsage}}|{{.CPUPerc}}' 2>/dev/null \
    | awk -F'|' -v want="$1" '
        $1 == want {
            split($2, a, " / "); v = a[1];
            unit = v; gsub(/[0-9.]/, "", unit);
            num  = v; gsub(/[^0-9.]/, "", num);
            mult = 1;
            if (unit == "KiB") mult = 1024;
            else if (unit == "MiB") mult = 1024*1024;
            else if (unit == "GiB") mult = 1024*1024*1024;
            else if (unit == "kB")  mult = 1000;
            else if (unit == "MB")  mult = 1000*1000;
            else if (unit == "GB")  mult = 1000*1000*1000;
            cpu = $3; gsub(/%/, "", cpu);
            printf "%d,%s", num * mult, cpu;
            found = 1
        }
        END { if (!found) printf "," }'
}

sample_row() {
    local ts elapsed head dbs imin imax cnt dbsize apimem pgmem target pct
    ts="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    elapsed=0
    [ -f "${START_MARKER}" ] && elapsed=$(( $(date -u +%s) - $(cat "${START_MARKER}") ))

    head="$(rpc_head)"
    dbs="$(db_stats)"
    imin="$(echo "${dbs}" | cut -d, -f1)"; imax="$(echo "${dbs}" | cut -d, -f2)"
    cnt="$(echo "${dbs}"  | cut -d, -f3)"; dbsize="$(echo "${dbs}" | cut -d, -f4)"
    apimem="$(mem_bytes qer-bsapi)"
    pgmem="$(mem_bytes qer-bsdb)"

    target=""; pct=""
    if [ -n "${head}" ]; then
        target=$(( head - FIRST_BLOCK + 1 ))
        if [ -n "${cnt:-}" ] && [ "${target}" -gt 0 ]; then
            pct="$(awk -v c="${cnt}" -v t="${target}" 'BEGIN{printf "%.3f", (c/t)*100}')"
        fi
    fi

    printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s\n' \
        "${ts}" "${elapsed}" "${head}" "${target}" "${imin}" "${imax}" \
        "${cnt}" "${pct}" "${dbsize}" "${apimem}" "${pgmem}"
}

CSV_HEADER='ts_utc,elapsed_s,rpc_head,target_blocks,indexed_min,indexed_max,consensus_blocks,pct_complete,db_bytes,bsapi_mem_bytes,bsapi_cpu_pct,bsdb_mem_bytes,bsdb_cpu_pct'

cmd_up() {
    gen_env
    mkdir -p "${OUT_DIR}"
    log "pulling images (blockscout 9.0.2 / frontend v2.3.5 / postgres 17-alpine)"
    dc pull --quiet
    log "starting stack"
    dc up -d
    date -u +%s >"${START_MARKER}"
    [ -f "${CSV}" ] || echo "${CSV_HEADER}" >"${CSV}"
    log "up. head=$(rpc_head) first_block=${FIRST_BLOCK}"
    log "UI  http://localhost:${REHEARSAL_UI_PORT:-3000}"
    log "API http://localhost:${REHEARSAL_API_PORT:-4000}/api/v2/main-page/indexing-status"
}

cmd_sample() {
    mkdir -p "${OUT_DIR}"
    [ -f "${CSV}" ] || echo "${CSV_HEADER}" >"${CSV}"
    local row; row="$(sample_row)"
    echo "${row}" >>"${CSV}"
    echo "${row}"
}

cmd_status() {
    local row head cnt target pct dbsize apimem
    row="$(sample_row)"
    head="$(echo "${row}"   | cut -d, -f3)"
    target="$(echo "${row}" | cut -d, -f4)"
    cnt="$(echo "${row}"    | cut -d, -f7)"
    pct="$(echo "${row}"    | cut -d, -f8)"
    dbsize="$(echo "${row}" | cut -d, -f9)"
    apimem="$(echo "${row}" | cut -d, -f10)"
    printf 'head=%s target=%s indexed=%s (%s%%) db=%s MiB bsapi=%s MiB\n' \
        "${head}" "${target}" "${cnt}" "${pct:-?}" \
        "$(( ${dbsize:-0} / 1048576 ))" "$(( ${apimem:-0} / 1048576 ))"
}

# Emits one line per tick and EXITS when the backfill is complete, so it can be
# driven by a Monitor. Fails loud rather than silent: a dead container or an
# unreachable RPC produces an ERROR line, not silence.
cmd_watch() {
    local stalls=0 last_cnt=-1
    while true; do
        if ! docker inspect -f '{{.State.Running}}' qer-bsapi 2>/dev/null | grep -q true; then
            echo "ERROR bsapi is not running — $(docker inspect -f '{{.State.Status}} exit={{.State.ExitCode}}' qer-bsapi 2>&1)"
            exit 1
        fi
        local row cnt target pct
        row="$(cmd_sample)"
        cnt="$(echo "${row}" | cut -d, -f7)"
        target="$(echo "${row}" | cut -d, -f4)"
        pct="$(echo "${row}" | cut -d, -f8)"

        if [ -z "${cnt}" ] || [ -z "${target}" ]; then
            echo "ERROR sampler could not read head or db (row: ${row})"
        else
            echo "backfill ${cnt}/${target} (${pct}%) elapsed=$(echo "${row}" | cut -d, -f2)s db=$(( $(echo "${row}" | cut -d, -f9) / 1048576 ))MiB"
            # Caught up: within one minute of blocks (10 x 6s) of the target.
            if [ "$(( target - cnt ))" -le 10 ]; then
                echo "DONE backfill complete at ${cnt}/${target} in $(echo "${row}" | cut -d, -f2)s"
                exit 0
            fi
            if [ "${cnt}" = "${last_cnt}" ]; then
                stalls=$(( stalls + 1 ))
                [ "${stalls}" -ge 5 ] && { echo "ERROR no progress for $(( stalls * INTERVAL ))s at ${cnt}/${target}"; exit 1; }
            else
                stalls=0
            fi
            last_cnt="${cnt}"
        fi
        sleep "${INTERVAL}"
    done
}

cmd_down() {
    dc down --volumes --remove-orphans
    rm -f "${START_MARKER}"
    log "stack down, volume removed"
}

case "${1:-}" in
    up)     cmd_up ;;
    sample) cmd_sample ;;
    watch)  cmd_watch ;;
    status) cmd_status ;;
    logs)   dc logs -f bsapi ;;
    down)   cmd_down ;;
    *) echo "usage: $0 {up|sample|watch|status|logs|down}" >&2; exit 2 ;;
esac
